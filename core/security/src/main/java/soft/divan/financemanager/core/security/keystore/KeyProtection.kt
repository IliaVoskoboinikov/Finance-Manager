package soft.divan.financemanager.core.security.keystore

/**
 * Когда ключ Android Keystore разрешено использовать.
 *
 * Условие задаётся при создании ключа и дальше не меняется: Keystore сам откажет в операции,
 * если условие не выполнено. Поэтому уровень защиты — свойство ключа, а не проверка в коде.
 */
enum class KeyProtection {

    /**
     * Без участия пользователя. Нужен уровню «ключ в Keystore»: фоновая синхронизация открывает
     * базу сама, в том числе при заблокированном экране.
     */
    ALWAYS_AVAILABLE,

    /**
     * Только на разблокированном устройстве (API 28+). Внешний слой уровня «PIN»: базу на этом
     * уровне и так открывает только пользователь, а на заблокированном экране ключ недоступен.
     */
    UNLOCKED_DEVICE,

    /**
     * Только после строгой биометрической аутентификации, отдельно на каждую операцию. Ключ
     * инвалидируется, если в системе появился новый отпечаток.
     */
    BIOMETRIC
}
