package soft.divan.financemanager.core.data.outbox

/**
 * Что случилось с одной записью очереди и как это влияет на прогон.
 *
 * Общий словарь [OutboxProcessor] и [OutboxEntryHandler]: первый решает, какие записи брать и в
 * каком порядке, второй — что делать с исходом отправки. [SKIPPED] возвращает только процессор:
 * до отправки дело не дошло.
 */
internal enum class OutboxEntryOutcome {

    /** Запись закрыта — подтверждена либо уведена в dead-letter. Прогон идёт дальше. */
    DONE,

    /** Записи не касались: её ждёт застрявший предшественник или её забрал параллельный прогон. */
    SKIPPED,

    /**
     * Операция осталась в очереди. Всё, что ждёт **её**, в этом проходе трогать нельзя;
     * независимые операции — можно и нужно.
     */
    STALLED,

    /** Отправлять сейчас нельзя вообще ничего: сеть заблокирована на стороне клиента. */
    RUN_STALLED
}
