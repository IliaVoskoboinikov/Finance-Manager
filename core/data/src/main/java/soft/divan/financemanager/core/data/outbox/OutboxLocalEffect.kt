package soft.divan.financemanager.core.data.outbox

/**
 * Локальная запись, которую нужно сделать по итогу успешной отправки операции.
 *
 * ### Зачем описание вместо действия
 * Успешная отправка меняет **два** факта в базе: доменную строку (появился `serverId`, снят
 * pending-статус) и запись очереди (операция закрыта). Если выполнять их по отдельности, между
 * ними появляется окно: процесс может умереть, оставив строку уже подтверждённой, а операцию —
 * незакрытой. По истечении аренды она уедет на сервер снова. Потери данных нет — идемпотентность
 * делает повтор безвредным, — но это лишний round-trip и разъезжающиеся друг с другом состояния.
 *
 * Поэтому отправитель не пишет в базу сам, а **описывает** нужную запись, а [OutboxProcessor]
 * применяет её одной транзакцией вместе с `markCompleted`. Обратный путь становится таким же
 * атомарным, как и прямой (постановка в очередь рядом с доменной записью).
 *
 * Чтение состояния, от которого зависит запись, тоже выполняется внутри [apply] — то есть внутри
 * транзакции, чтобы решение принималось по актуальным данным.
 */
fun interface OutboxLocalEffect {

    /** Выполняется внутри транзакции; бросок исключения откатывает и закрытие записи очереди. */
    suspend fun apply()
}
