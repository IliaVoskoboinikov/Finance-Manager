package soft.divan.financemanager.core.loggingerror

/**
 * Логирование нефатальных ошибок в краш-репортинг.
 *
 * Для пойманных исключений используйте форму с [Throwable] — тогда в отчёт попадают
 * оригинальный стек, имена типов и цепочка `cause`. Строковая форма — только для логических
 * ошибок, у которых нет исключения (некорректный ответ сервера, нарушенный инвариант и т.п.).
 *
 * Текст исключения в отчёт не попадает — реализация отправляет только типы и стек. Строки,
 * которые передаются сюда (`message`, логическая ошибка), уходят как есть: в них —
 * фиксированный текст и идентификаторы, коды, имена типов. Никогда не подставляйте в них
 * `throwable.message` или данные пользователя (суммы, комментарии, email, токены).
 */
interface ErrorLogger {

    /**
     * Записать пойманное исключение [throwable] с сохранением стека/типа/cause.
     * [message] — необязательный контекст (что именно делали в момент сбоя).
     */
    fun recordError(throwable: Throwable, message: String? = null)

    /** Записать логическую ошибку без исключения. */
    fun recordError(message: String)
}
