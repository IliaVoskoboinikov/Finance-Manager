package soft.divan.financemanager.core.database.util

interface DatabaseCleanupManager {
    /**
     * Стирает все пользовательские данные — счета, транзакции, очередь исходящих операций.
     *
     * Стирание криптографическое: удаляются файл базы и её ключ, и создаётся новая база, в которую
     * заново засеян справочник категорий. Удалять строки `DELETE`-ом недостаточно — SQLite
     * оставляет их в свободных страницах файла, и с тем же ключом они читаемы.
     */
    suspend fun clearUserData()
}
