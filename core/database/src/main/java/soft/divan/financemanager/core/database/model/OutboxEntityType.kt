package soft.divan.financemanager.core.database.model

/**
 * Тип доменной сущности, которой принадлежит запись outbox.
 *
 * Нужен, чтобы `OutboxProcessor` знал, в какой эндпоинт отправлять снимок запроса, и чтобы
 * соблюдать порядок синхронизации: счёт должен доехать до сервера раньше своих транзакций.
 *
 * Категории не участвуют: они приходят с сервера только на чтение (pull), клиент их не создаёт.
 */
enum class OutboxEntityType {
    ACCOUNT,
    TRANSACTION
}
