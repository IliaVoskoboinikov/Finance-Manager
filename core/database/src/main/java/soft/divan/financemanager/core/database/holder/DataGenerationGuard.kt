package soft.divan.financemanager.core.database.holder

/**
 * Привязка работы к данным, которые лежали в базе, когда она началась.
 *
 * Синк сначала идёт в сеть — без аренды базы, иначе выход из аккаунта ждал бы таймаута запроса, —
 * и только потом пишет ответ. Если за время запроса базу стёрли ([DatabaseHolder.wipe]: выход с
 * очисткой, забытый PIN), ответ прошлого пользователя попал бы в новую базу — к гостю или к
 * следующему пользователю. Работа, привязанная через [bindToCurrentData], после стирания к базе
 * уже не допускается.
 *
 * Отдельным интерфейсом — чтобы синку не нужен был весь [DatabaseHolder] с открытием и стиранием.
 */
interface DataGenerationGuard {

    /**
     * Выполняет [block], привязав его к нынешним данным: разовое обращение к базе
     * (`withDatabase`) изнутри блока после стирания получает [StaleDataException]. Запирание и
     * открытие базы (уровень PIN) привязку не рвут — данные те же.
     *
     * Вложенный вызов сохраняет внешнюю привязку: работа принадлежит данным, на которых началась.
     *
     * Проверяют поколение только разовые обращения (`withDatabase`), а `observe` — нет: поток
     * после стирания отдаёт уже новые данные. Чтение безвредно, а запись по нему пойдёт через
     * `withDatabase` и будет отклонена.
     */
    suspend fun <T> bindToCurrentData(block: suspend () -> T): T
}

/** Данные, к которым была привязана работа ([DataGenerationGuard]), стёрты. */
class StaleDataException : IllegalStateException("Local data was wiped while the work was running")
