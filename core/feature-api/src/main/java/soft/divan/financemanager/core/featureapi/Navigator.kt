package soft.divan.financemanager.core.featureapi

import androidx.navigation3.runtime.NavKey

/**
 * Навигация, доступная фиче.
 *
 * В Navigation 3 back stack — это обычный список ключей, которым владеет хост
 * (модуль `app`). Фича не должна знать, как этот список устроен: лежит ли он в одном
 * общем стеке или в отдельном стеке вкладки нижней навигации. Поэтому вместо самого
 * списка фиче передаётся этот интерфейс.
 */
interface Navigator {

    /** Открывает экран [key], добавляя его на вершину текущего стека. */
    fun goTo(key: NavKey)

    /** Возвращается на предыдущий экран. Если стек уже на корневом экране — ничего не делает. */
    fun back()
}
