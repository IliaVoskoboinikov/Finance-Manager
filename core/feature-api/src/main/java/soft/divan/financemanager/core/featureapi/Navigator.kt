package soft.divan.financemanager.core.featureapi

import androidx.navigation3.runtime.NavKey

/**
 * Навигация, доступная фиче.
 *
 * В Navigation 3 back stack — это обычный список ключей, которым владеет хост
 * (модуль `app`). Фича не должна знать, как этот список устроен: лежит ли он в одном
 * общем стеке или в отдельном стеке вкладки нижней навигации. Поэтому вместо самого
 * списка фиче передаётся этот интерфейс.
 *
 * Обе операции идемпотентны: повторный тап по кнопке не должен открыть экран второй раз
 * или закрыть лишний.
 */
interface Navigator {

    /**
     * Открывает экран [key], добавляя его на вершину текущего стека.
     *
     * Если [key] уже на вершине, ничего не делает: двойной тап по строке списка иначе положил бы
     * в стек два одинаковых ключа, а Navigation 3 требует уникальный ключ у каждой записи.
     */
    fun goTo(key: NavKey)

    /**
     * Закрывает экран [from] и возвращается на предыдущий.
     *
     * Ничего не делает, если [from] уже не на вершине стека: второй тап по «назад» или
     * «назад» по событию после закрытия экрана иначе закрыли бы экран под ним.
     */
    fun back(from: NavKey)
}
