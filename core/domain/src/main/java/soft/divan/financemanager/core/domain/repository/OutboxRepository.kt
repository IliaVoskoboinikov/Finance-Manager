package soft.divan.financemanager.core.domain.repository

import kotlinx.coroutines.flow.Flow
import soft.divan.financemanager.core.domain.result.DomainResult

/**
 * Состояние очереди исходящих операций с точки зрения пользователя.
 *
 * Обычная синхронизация идёт молча и в фоне, но операции, которые сервер отверг по существу или
 * которые не удалось отправить за все попытки, замолкать не должны: иначе пользователь считает
 * изменения сохранёнными, а на других устройствах их нет. Этот контракт даёт минимум для
 * честного поведения — показать, что часть операций не доехала, и позволить повторить.
 */
interface OutboxRepository {

    /** Сколько операций ждут разбора в dead-letter. Ноль — синхронизация в порядке. */
    fun observeFailedCount(): Flow<DomainResult<Int>>

    /**
     * Возвращает отложенные операции в очередь по команде пользователя и сразу пробует отправить.
     *
     * Осмысленно после устранения причины (появилась сеть, исправлены данные): автоматических
     * попыток у таких записей больше не осталось.
     */
    suspend fun retryFailed(): DomainResult<Unit>
}
