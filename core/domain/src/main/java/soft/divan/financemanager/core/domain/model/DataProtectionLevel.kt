package soft.divan.financemanager.core.domain.model

/**
 * Чем защищён ключ локальной базы.
 *
 * Сам файл базы зашифрован на любом уровне — уровни различаются тем, где и как хранится ключ.
 * Модель угроз каждого уровня — `docs/encryption.md`.
 */
enum class DataProtectionLevel {

    /** Ключ хранится рядом с базой открыто: защищает только от чтения одного файла базы. */
    NONE,

    /**
     * Ключ завёрнут неизвлекаемым ключом Android Keystore: скопированные с телефона файлы
     * бесполезны. База открывается без участия пользователя — фоновая синхронизация работает.
     */
    DEVICE,

    /**
     * Ключ завёрнут ключом из PIN, а снаружи — ключом Keystore: без PIN базу не открыть и на этом
     * телефоне. Фоновой синхронизации нет, забытый PIN означает стирание данных.
     */
    PIN
}
